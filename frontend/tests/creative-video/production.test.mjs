import assert from 'node:assert/strict';
import {generate,settle,cancel,reconcile,adoptVersion,startRender,topup} from '../../apps/web-ele/src/api/creative-video/production.ts';
import {createQuote,validateQuote} from '../../apps/web-ele/src/api/creative-video/billing.ts';
globalThis.localStorage={getItem:()=>null};
const shot={id:1,text:'纸张破碎',seconds:8,revision:1,versions:[]};
const p={shots:[shot],jobs:[],ledger:[],balance:120,sequence:0,renders:[]};
const quote=createQuote(shot);assert.equal(quote.cost,24);
generate(p,shot,false,quote);assert.equal(p.balance,96);assert.throws(()=>generate(p,shot,false),/进行中/);
settle(p,Infinity);settle(p,Infinity);assert.equal(p.ledger.length,2);assert.equal(shot.versions.length,1);
adoptVersion(p,1,1);shot.revision++;assert.equal(shot.adopted,1);
generate(p,shot,false);p.jobs.at(-1).timeout=true;settle(p,Infinity);assert.equal(p.jobs.at(-1).status,'reconciling');assert.equal(p.balance,72);
reconcile(p,p.jobs.at(-1),'failed');reconcile(p,p.jobs.at(-1),'failed');assert.equal(p.balance,96);
generate(p,shot,false);cancel(p,p.jobs.at(-1));assert.equal(p.balance,72);assert.equal(p.jobs.at(-1).status,'reconciling');reconcile(p,p.jobs.at(-1),'failed');assert.equal(p.balance,96);
const expired=createQuote(shot);assert.throws(()=>validateQuote(expired,shot,Infinity),/过期/);
const changed=createQuote(shot);shot.text='新剧情';assert.throws(()=>validateQuote(changed,shot),/INPUT_REVISION_CHANGED/);
const multiple=createQuote(shot,'premium','1080p',2);assert.equal(multiple.cost,120);assert.throws(()=>generate(p,shot,false,multiple),/不足/);
topup(p,100);generate(p,shot,false,multiple);settle(p,Infinity);assert.equal(shot.versions.length,3);
const render=startRender(p);const snapshot=render.shots;shot.text='后续编辑';assert.equal(render.shots,snapshot);settle(p,Infinity);assert.equal(render.status,'success');
globalThis.localStorage={getItem:()=> 'reviewer'};assert.throws(()=>createQuote(shot),/无权/);
console.log('通过：8s=24积分、冻结结算、重复处理、超时和取消对账、报价过期与修订冲突、多候选、充值、正式版本保留、合成快照、权限');
